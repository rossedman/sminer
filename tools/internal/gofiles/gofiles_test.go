package gofiles

import (
	"errors"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"testing"
)

// write creates files (path -> content) under root.
func write(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for p, c := range files {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(c), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

func TestWalk(t *testing.T) {
	files := map[string]string{
		"a.go":              "package m\n",
		"a_test.go":         "package m\n",
		"gen.go":            "// Code generated by x. DO NOT EDIT.\n\npackage m\n",
		"notgo.txt":         "hello",
		"sub/b.go":          "package sub\n",
		"sub/deep/c.go":     "package deep\n",
		"testdata/t.go":     "package bad syntax(((",
		"vendor/v.go":       "package bad syntax(((",
		".hidden/h.go":      "package bad syntax(((",
		"sub/testdata/t.go": "package bad syntax(((",
	}
	tests := []struct {
		name     string
		patterns []string
		want     map[string]bool // path -> generated
	}{
		{"default is recursive", nil, map[string]bool{"a.go": false, "gen.go": true, "sub/b.go": false, "sub/deep/c.go": false}},
		{"explicit recursive", []string{"./..."}, map[string]bool{"a.go": false, "gen.go": true, "sub/b.go": false, "sub/deep/c.go": false}},
		{"non-recursive dir", []string{"sub"}, map[string]bool{"sub/b.go": false}},
		{"dot is non-recursive", []string{"."}, map[string]bool{"a.go": false, "gen.go": true}},
		{"subtree", []string{"sub/..."}, map[string]bool{"sub/b.go": false, "sub/deep/c.go": false}},
		{"multiple patterns", []string{"sub", "."}, map[string]bool{"sub/b.go": false, "a.go": false, "gen.go": true}},
	}
	root := t.TempDir()
	write(t, root, files)
	t.Chdir(root)
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := map[string]bool{}
			err := Walk(tt.patterns, func(f File) error {
				if f.Fset == nil || f.AST == nil {
					t.Errorf("%s: missing Fset/AST", f.Path)
				}
				got[f.Path] = f.Generated
				return nil
			})
			if err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("files = %v, want %v", got, tt.want)
			}
		})
	}
}

func TestWalkErrors(t *testing.T) {
	root := t.TempDir()
	write(t, root, map[string]string{"ok.go": "package m\n", "bad/bad.go": "package bad syntax((("})
	t.Chdir(root)

	t.Run("callback error stops the walk", func(t *testing.T) {
		boom := errors.New("boom")
		var calls int
		err := Walk([]string{"."}, func(File) error { calls++; return boom })
		if !errors.Is(err, boom) || calls != 1 {
			t.Errorf("err = %v after %d calls", err, calls)
		}
	})
	t.Run("syntax error", func(t *testing.T) {
		if err := Walk([]string{"bad"}, func(File) error { return nil }); err == nil {
			t.Error("expected parse error")
		}
	})
	t.Run("missing root", func(t *testing.T) {
		if err := Walk([]string{"nope/..."}, func(File) error { return nil }); err == nil {
			t.Error("expected error for missing directory")
		}
	})
	if os.Geteuid() != 0 { // root reads anything
		t.Run("unreadable file", func(t *testing.T) {
			write(t, root, map[string]string{"locked/l.go": "package l\n"})
			p := filepath.Join(root, "locked", "l.go")
			if err := os.Chmod(p, 0); err != nil {
				t.Fatal(err)
			}
			if err := Walk([]string{"locked"}, func(File) error { return nil }); err == nil {
				t.Error("expected read error")
			}
		})
	}
}

func TestWalkPathsSorted(t *testing.T) {
	root := t.TempDir()
	write(t, root, map[string]string{"b.go": "package m\n", "a.go": "package m\n", "c/c.go": "package c\n"})
	t.Chdir(root)
	var got []string
	if err := Walk(nil, func(f File) error { got = append(got, f.Path); return nil }); err != nil {
		t.Fatal(err)
	}
	if !sort.StringsAreSorted(got) || len(got) != 3 {
		t.Errorf("paths = %v", got)
	}
}
