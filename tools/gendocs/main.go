// Command gendocs writes one Markdown reference page per sminer command into
// docs/reference/commands, so the docs site never drifts from the CLI.
//
// Usage: go run ./tools/gendocs
package main

import (
	"fmt"
	"os"

	"github.com/spf13/cobra/doc"

	"github.com/rossedman/sminer/internal/cli"
)

// main regenerates the reference pages, replacing any from an earlier run.
func main() {
	if err := generate("docs/reference/commands"); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
}

// generate clears dir and writes a page for every available command into it.
func generate(dir string) error {
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	root := cli.Command()
	root.DisableAutoGenTag = true
	return doc.GenMarkdownTreeCustom(root, dir, prepend, link)
}

// prepend marks each page as generated, for readers of the Markdown source.
func prepend(string) string {
	return "<!-- Generated by tools/gendocs from the CLI. Do not edit; run `make docs`. -->\n\n"
}

// link keeps cross-references as the relative file names MkDocs resolves.
func link(name string) string { return name }
