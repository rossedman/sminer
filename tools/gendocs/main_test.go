package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGenerate(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "commands")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(dir, "sminer_removed.md")
	if err := os.WriteFile(stale, []byte("old"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := generate(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Errorf("page for a removed command survived: %v", err)
	}
	for _, page := range []string{"sminer.md", "sminer_run.md", "sminer_finding_accept.md", "sminer_config_show.md"} {
		b, err := os.ReadFile(filepath.Join(dir, page))
		if err != nil {
			t.Errorf("missing %s: %v", page, err)
			continue
		}
		if !strings.HasPrefix(string(b), "<!-- Generated by tools/gendocs") {
			t.Errorf("%s lacks the generated marker", page)
		}
	}
	root, _ := os.ReadFile(filepath.Join(dir, "sminer.md"))
	if !strings.Contains(string(root), "(sminer_finding.md)") {
		t.Error("root page should link subcommands by relative file name")
	}
	for _, hidden := range []string{"sminer_show.md", "sminer_accept.md"} {
		if _, err := os.Stat(filepath.Join(dir, hidden)); err == nil {
			t.Errorf("deprecated alias %s got a page", hidden)
		}
	}
}
