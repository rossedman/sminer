func parseFile(t *testing.T, src string) gofiles.File {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "x/f.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	return gofiles.File{Path: "x/f.go", Fset: fset, AST: f}
}

func TestFuncsWithoutDoc(t *testing.T) {
	t.Parallel()
	src := `package x

// Documented has a comment.
func Documented() {}

func Plain() {}

type T struct{}

func (T) Value() {}

func (*T) Pointer() {}

// Ok is documented.
func (t T) Ok() {}

type G[A any] struct{}

func (G[A]) Generic() {}

func (*G[A]) GenericPtr() {}

type M[K comparable, V any] struct{}

func (M[K, V]) Multi() {}

var _ = 1
`
	got := funcsWithoutDoc(parseFile(t, src))
	want := []string{
		"x/f.go:6: Plain has no doc comment",
		"x/f.go:10: T.Value has no doc comment",
		"x/f.go:12: T.Pointer has no doc comment",
		"x/f.go:19: G.Generic has no doc comment",
		"x/f.go:21: G.GenericPtr has no doc comment",
		"x/f.go:25: M.Multi has no doc comment",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got\n%q\nwant\n%q", got, want)
	}
	if got := funcsWithoutDoc(parseFile(t, "package x\n\n// F is.\nfunc F() {}\n")); len(got) != 0 {
		t.Errorf("documented file reported %v", got)
	}
}

func TestCheck(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"good/g.go":      "// Package good is fine.\npackage good\n\n// F is documented.\nfunc F() {}\n",
		"nodoc/n.go":     "package nodoc\n\nfunc G() {}\n",
		"split/a.go":     "// Package split has its comment in one file.\npackage split\n",
		"split/b.go":     "package split\n\n// B is documented.\nfunc B() {}\n",
		"gen/gen.go":     "// Code generated by x. DO NOT EDIT.\n\npackage gen\n\nfunc Undocumented() {}\n",
		"good/g_test.go": "package good\n\nfunc TestX() {}\n",
		"testdata/td.go": "package td\n\nfunc Z() {}\n",
	}
	for p, c := range files {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(c), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	t.Chdir(root)

	got, err := check([]string{"./..."})
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"nodoc/n.go:3: G has no doc comment",
		"nodoc: package has no package comment",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got\n%q\nwant\n%q", got, want)
	}

	got, err = check([]string{"good", "split"})
	if err != nil || len(got) != 0 {
		t.Errorf("clean packages: %q, %v", got, err)
	}

	if err := os.WriteFile("broken.go", []byte("package ((("), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := check([]string{"."}); err == nil {
		t.Error("expected parse error")
	}
}

func TestMainCleanTree(t *testing.T) {
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "ok.go"), []byte("// Package ok is documented.\npackage ok\n\n// F is documented.\nfunc F() {}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Chdir(root)
	r, w, err := os.Pipe()
	if err != nil {
		t.Fatal(err)
	}
	oldOut, oldArgs := os.Stdout, os.Args
	os.Stdout, os.Args = w, []string{"doccheck", "./..."}
	t.Cleanup(func() { os.Stdout, os.Args = oldOut, oldArgs })

	main() // a clean tree returns instead of exiting

	w.Close()
	os.Stdout = oldOut
	if out, _ := io.ReadAll(r); len(out) != 0 {
		t.Errorf("clean tree printed %q", out)
	}
}
